// Creates backend/local-dev/.env (secrets + anon/service JWTs) and points the
// web app at the local gateway via frontend/web/.env.development.local.
// Safe to re-run: existing secrets are kept.
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '../..')
const envPath = path.join(here, '.env')
const webEnvPath = path.join(root, 'frontend/web/.env.development.local')

function readEnv(p) {
  if (!fs.existsSync(p)) return {}
  const out = {}
  for (const line of fs.readFileSync(p, 'utf8').split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/)
    if (m) out[m[1]] = m[2]
  }
  return out
}

function b64url(input) {
  return Buffer.from(input).toString('base64url')
}

function signJwt(payload, secret) {
  const head = b64url(JSON.stringify({ alg: 'HS256', typ: 'JWT' }))
  const body = b64url(JSON.stringify(payload))
  const sig = crypto.createHmac('sha256', secret).update(`${head}.${body}`).digest('base64url')
  return `${head}.${body}.${sig}`
}

const env = readEnv(envPath)
env.POSTGRES_PASSWORD ||= crypto.randomBytes(18).toString('hex')
env.JWT_SECRET ||= crypto.randomBytes(32).toString('hex')
env.GATEWAY_PORT ||= '54321'
env.POSTGRES_PORT ||= '54322'
env.API_URL ||= `http://localhost:${env.GATEWAY_PORT}`
env.SITE_URL ||= 'http://localhost:5173'
const iat = Math.floor(Date.now() / 1000)
const exp = iat + 10 * 365 * 24 * 3600
env.ANON_KEY ||= signJwt({ role: 'anon', iss: 'consultancy-local', iat, exp }, env.JWT_SECRET)
env.SERVICE_ROLE_KEY ||= signJwt({ role: 'service_role', iss: 'consultancy-local', iat, exp }, env.JWT_SECRET)
env.RESEND_API_KEY ??= ''

fs.writeFileSync(
  envPath,
  '# Local-only secrets generated by gen-env.mjs. Do not commit.\n' +
    Object.entries(env)
      .map(([k, v]) => `${k}=${v}`)
      .join('\n') +
    '\n',
)

fs.writeFileSync(
  webEnvPath,
  [
    '# Generated by backend/local-dev/gen-env.mjs: `npm run dev` uses the local stack.',
    '# Delete this file to point the dev server back at frontend/web/.env (Railway).',
    `VITE_SUPABASE_URL=${env.API_URL}`,
    `VITE_SUPABASE_ANON_KEY=${env.ANON_KEY}`,
    'VITE_PDF_SERVICE_URL=/api/pdf',
    '',
  ].join('\n'),
)

console.log(`wrote ${path.relative(root, envPath)} and ${path.relative(root, webEnvPath)}`)
